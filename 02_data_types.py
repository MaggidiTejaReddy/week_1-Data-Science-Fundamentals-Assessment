# Part 2: Python Data Types

print("DATA TYPES")
print("-" * 40)

# Integer
age = 20

# Float
percentage = 85.5

# String
name = "Rakesh"

# Boolean
is_student = True

# List
marks = [85, 78, 92, 88]

# Tuple
coordinates = (17.3850, 78.4867)

# Set
subjects = {"Python", "Statistics", "Machine Learning"}

# Dictionary
student = {
    "name": "Rakesh",
    "age": 20,
    "branch": "AIML",
    "marks": 85
}

print("Integer:", age)
print("Float:", percentage)
print("String:", name)
print("Boolean:", is_student)
print("List:", marks)
print("Tuple:", coordinates)
print("Set:", subjects)
print("Dictionary:", student)

print("\nData Types:")

print(type(age))
print(type(percentage))
print(type(name))
print(type(is_student))
print(type(marks))
print(type(coordinates))
print(type(subjects))
print(type(student))